def _down(fc: dict) -> float:
    """The bad-month figure the tail gate uses: the stock's own (absolute) 10% outcome when calibrated (E22)."""
    return fc["q10_abs"] if fc.get("q10_abs") is not None else fc["q10"]


def _shrink_story(fc: dict) -> str:
    """How the raw forecast becomes the shrunk one, part by part (E19, E23), so the numbers reconcile on the page."""
    if fc.get("shrink_common") is None or fc.get("mu_common") is None:
        return (f"Its bootstrap standard error is {pct(fc['se'], sign=False)}, so it keeps {fc['shrink_factor']:.0%} of "
                f"the forecast: the shrunk forecast used for decisions is {pct(fc['mu_shrunk'])}.")
    c, sp = fc["mu_common"], fc["mu_specific"]
    fcm, fsp = fc["shrink_common"], fc["shrink_specific"]
    cap = ""
    tau, se_s = fc.get("tau") or 0.005, fc.get("se_specific") or 0.0
    bayes = tau * tau / (tau * tau + se_s * se_s)
    if fsp < bayes - 1e-9:  # E23: the out-of-sample slope, not the bootstrap, set this factor
        cap = (f" (capped at {fsp:.0%}: the share of predicted differences between stocks that actually showed up in "
               f"held-out data; the bootstrap alone would have kept {bayes:.0%})")
    return (f"That raw figure is the sum of two parts. The market-timing part, the same for every stock today, is "
            f"{pct(c)} with a bootstrap standard error of {pct(fc['se_common'], sign=False)}: so uncertain that only "
            f"{fcm:.0%} of it is kept ({pct(fcm * c)}). The stock-specific part is {pct(sp)} with a standard error of "
            f"{pct(fc['se_specific'], sign=False)}: {fsp:.0%} of it is kept{cap} ({pct(fsp * sp)}). Together: the shrunk "
            f"forecast used for decisions is {pct(fc['mu_shrunk'])}. It can be larger than the raw figure when an "
            f"unreliable negative market part was hiding a reliable positive stock part.")


def _top(items, n, positive=True):
    xs = [i for i in items if i["contribution"] is not None and (i["contribution"] > 0) == positive and i["contribution"] != 0]
    return sorted(xs, key=lambda i: -abs(i["contribution"]))[:n]


def _feature_phrase(it, card) -> str:
    f = it["feature"]
    info = FEATURE_INFO[f]
    raw = (card.get("features") or {}).get(f)
    x = it["x"]
    if info.get("market"):
        level = f"z = {x:+.2f}" if x is not None else "unknown"
    else:
        level = f"rank {x + 0.5:.0%} of stocks" if x is not None else "unknown"
    raw_txt = ""
    if raw is not None:
        if f in ("mom_12_1", "rev_5", "ret_20", "gap_1", "mkt_20", "mkt_60"):
            raw_txt = f", value {pct(raw)}"
        elif f in ("vol_20", "park_20", "mkt_vol_20"):
            raw_txt = f", {pct(raw, sign=False)} a day"
        elif f == "range_250":
            raw_txt = f", {raw:.0%} of the way from the 1-year low to the high"
        elif f == "breadth_50":
            raw_txt = f", {raw:.0%} of stocks above their 50-session average"
        elif f == "lvalue_20":
            raw_txt = f", median traded value {crore(math.exp(raw))}"
        elif f == "amihud_20":
            raw_txt = f", {raw:.4f}"
    sign = "adds" if it["contribution"] > 0 else "subtracts"
    return (f"{info['name']} ({level}{raw_txt}) {sign} {pct(abs(it['contribution']), sign=False)} "
            f"(β = {it['beta']:+.4f})")


def narrative(card: dict, ranking: dict) -> list[dict]:
    """Sections of plain text for one stock card, in reading order."""
    pol = ranking.get("policy", {})
    h = ranking.get("h", 20)
    cls = card["class"]
    info = CLASS_INFO[cls]
    out = [{"title": "The call", "text": f"{info['title']}. {info['means']} " +
            " ".join(reason_text(r) for r in card.get("reasons", []))}]
    if cls in ("INELIGIBLE",) or (cls == "AVOID" and "forecast" not in card):
        failed = [c for c in card.get("checks", []) if c["pass"] is False]
        unknown = [c for c in card.get("checks", []) if c["pass"] is None]
        txt = "Failed: " + "; ".join(f"{c['rule'].replace('_', ' ').lower()} ({c['value']} vs {c['need']})" for c in failed) \
            if failed else "No structural rule failed."
        if unknown:
            txt += " Unknown: " + ", ".join(c["rule"].replace("_", " ").lower() for c in unknown) + "."
        out.append({"title": "Eligibility", "text": txt})
        return out
    if cls == "NO_FORECAST":
        hist = card.get("history") or {}
        txt = (f"Missing: {', '.join(card.get('missing_features') or []) or 'none'}. It has {hist.get('sessions_with_bars')} "
               f"sessions of bars under this ISIN (first {hist.get('first_bar')}); features need {hist.get('needed')} clean sessions.")
        if hist.get("unexplained_jumps"):
            txt += (f" Unexplained price jumps on {', '.join(hist['unexplained_jumps'])}: without a listed split/bonus "
                    "the true return that day is unknown, so windows containing it are not used.")
        if hist.get("isin_started"):
            txt += f" This ISIN started trading on {hist['isin_started'][0]} (a new ISIN, usually after a split)."
        out.append({"title": "Why there is no forecast", "text": txt})
        return out
    fc, costs, gates, flip = card["forecast"], card["costs"], card["gates"], card.get("flip", {})
    out.append({"title": "What the model expects",
                "text": f"Over the next {h} sessions (about {h / 20:.0f} month{'s' if h > 20 else ''}), from the next open, the "
                        f"model's raw forecast of the return versus the Nifty 50 is {pct(fc['mu_hat'])}. "
                        + _shrink_story(fc)
                        + f" A typical {h}-session move for this stock is ±{pct(fc['sigma_hat'], sign=False)}. Against the "
                        f"Nifty 50: 10% of outcomes below {pct(fc['q10'])}, median {pct(fc['q50'])}, 10% above "
                        f"{pct(fc['q90'])}."
                        + (f" The stock's own return (your money, assuming no market drift): 10% below "
                           f"{pct(fc['q10_abs'])}, median {pct(fc['q50_abs'])}, 10% above {pct(fc['q90_abs'])}."
                           if fc.get('q10_abs') is not None else "")
                        + f" Probability of beating the index before costs: {fc['p_positive']:.0%}."})
    con = card["contributions"]
    pos, neg = _top(con["items"], 3, True), _top(con["items"], 3, False)
    txt = (f"Raw forecast {pct(fc['mu_hat'])} = common part {pct(con['common_total'])} (intercept {pct(con['intercept'])} plus "
           f"market backdrop {pct(con['market_total'])}, the same for every stock today) + stock-specific part "
           f"{pct(con['stock_total'])}.")
    if pos:
        txt += " Pushing it up: " + "; ".join(_feature_phrase(i, card) for i in pos) + "."
    if neg:
        txt += " Pulling it down: " + "; ".join(_feature_phrase(i, card) for i in neg) + "."
    out.append({"title": "Why: what drives the forecast", "text": txt})
    out.append({"title": "Costs at your position size",
                "text": (f"{costs['q']} shares at {rupees(card['close'])} = {rupees(costs['value'])} (the per-stock cap is "
                         f"{rupees(pol.get('cap_rupees'))}). " if costs.get('q') else
                         f"Not even one share fits: one costs {rupees(card['close'])}, above the per-stock cap of "
                         f"{rupees(pol.get('cap_rupees'))}. The figures below are for ONE share, for reference only. ")
                        + f"Charges for buying and selling: {rupees(costs['charges'])} "
                        f"(buy {rupees(costs['buy_charges'])}, sell including the ₹{costs['dp_charge']} DP charge "
                        f"{rupees(costs['sell_charges_incl_dp'])}); modelled slippage {rupees(costs['slippage_rupees'])} "
                        f"({pct(costs['slippage_fraction'], sign=False)} both ways). Total round trip "
                        f"{pct(costs['cost_fraction'], sign=False)} of the position. A paper buy would be a limit order at "
                        f"{rupees(costs['limit_price'])} with {rupees(float(costs['cash_blocked']))} blocked."})
    edge_ok = "EDGE_BELOW_COST_AT_QUANTITY" not in gates["at_quantity"]
    tail_ok = "TAIL_LIMIT_AT_QUANTITY" not in gates["at_quantity"]
    out.append({"title": "The two gates",
                "text": f"Edge gate: shrunk forecast {pct(fc['mu_shrunk'])} - cost {pct(costs['cost_fraction'], sign=False)} = "
                        f"{pct(gates['net_edge'])}; it must be at least the minimum edge {pct(pol.get('min_edge'), sign=False)} → "
                        f"{'pass' if edge_ok else 'fail'}. Tail gate (money lost, not return versus the index): the stock's own 10% outcome {pct(_down(fc))} - cost = "
                        f"{pct(_down(fc) - costs['cost_fraction'])} on the position, which is "
                        f"{pct((costs.get('value') or 0) / (pol.get('W') or 1), 0, sign=False)} of capital, so "
                        f"{pct((costs.get('value') or 0) / (pol.get('W') or 1) * (_down(fc) - costs['cost_fraction']))} of capital; "
                        f"it must be at least -{pct(pol.get('tail_limit'), sign=False)} "
                        f"→ {'pass' if tail_ok else 'fail'}. Equivalently, the stock's own bad month must be no worse than "
                        f"{pct(flip.get('tail_q10_threshold'))} at this position size."
                        + (f" P(excess return covers the costs) = {card['p_beats_costs']:.0%}." if card.get("p_beats_costs") is not None else "")})
    out.append({"title": "What would change the call", "text": flip_text(card, pol)})
    if card.get("allocation", {}).get("selected"):
        a = card["allocation"]
        out.append({"title": "Allocation", "text": f"The allocator would hold {a['q']} shares ({rupees(a['value'])}) as one of "
                    f"at most {pol.get('K')} positions."})
    return out


def flip_text(card: dict, pol: dict) -> str:
    f, fc = card.get("flip") or {}, card["forecast"]
    cls = card["class"]
    parts = []
    if cls in ("BUY_CANDIDATE", "QUALIFIES"):
        parts.append(f"The shrunk forecast could fall by {pct(f.get('edge_margin'), sign=False)} before the edge gate fails, "
                     f"and the 10% outcome by {pct(f.get('tail_margin'), sign=False)} before the tail gate fails.")
    elif cls == "AVOID":
        parts.append(f"It is {pct(f.get('avoid_margin'), sign=False)} below the avoid threshold {pct(f.get('avoid_threshold'))}; "
                     f"a buy would need {pct(f.get('edge_threshold'))}.")
    if f.get("needed_rise_shrunk") is not None and cls not in ("BUY_CANDIDATE", "QUALIFIES"):
        parts.append(f"To clear the edge gate the shrunk forecast must rise by {pct(f['needed_rise_shrunk'], sign=False)} "
                     f"(the raw forecast by about {pct(f.get('needed_rise_mu_hat'), sign=False)} at today's shrinkage).")
        b = f.get("best_single_lever")
        if b:
            name = FEATURE_INFO[b["feature"]]["name"]
            parts.append(f"The strongest single lever is {name}: moving it to the {'top' if b['to_rank'] > 0 else 'bottom'} "
                         f"of today's ranks would add at most {pct(b['max_gain_shrunk'], sign=False)} to the shrunk forecast, "
                         + ("which would be enough on its own." if f.get("one_feature_could_clear") else
                            "not enough on its own: several signals would have to improve together."))
    if cls == "HIGH_RISK" or (f.get("tail_margin") is not None and f["tail_margin"] < 0):
        parts.append(f"The tail gate is short by {pct(-f['tail_margin'], sign=False)}: the stock would need to be calmer (its "
                     "10% outcome is the forecast minus about 1.3 typical moves), or the position smaller, for a bad "
                     f"month to cost the account less than the {pct(pol.get('tail_limit'), 0, sign=False)} tail limit.")
    bigger = card.get("costs", {}).get("bigger_accounts") or []
    if len(bigger) > 1 and cls not in ("BUY_CANDIDATE", "QUALIFIES"):
        parts.append("Account size: round-trip cost is " + ", ".join(
            f"{pct(b['cost_fraction'], sign=False)} on {rupees(b['position'], 0)}" for b in bigger) + " (the fixed DP charge "
            "and rupee rounding matter less on bigger positions).")
    return " ".join(parts) or "Nothing close to a threshold."



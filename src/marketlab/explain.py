def insights(card: dict, ranking: dict) -> list[dict]:
    """Rules that read several numbers together. Each: code, title, text, terms (glossary keys)."""
    out = []
    pol = ranking.get("policy", {})

    def add(code, title, text, terms=()):
        out.append({"code": code, "title": title, "text": text, "terms": list(terms)})
    if ranking.get("validation", {}).get("status") != "PROMOTED":
        add("UNVALIDATED_MODEL", "Research view, not validated",
            "This model has not passed the walk-forward evaluation and frozen promotion rule. Its forecasts may have no "
            "real skill; use the classes as a structured screen and check the reasons yourself.", ("promotion", "walk_forward"))
    fc, costs = card.get("forecast"), card.get("costs")
    feats = card.get("features") or {}
    if fc and costs:
        mu, sg, cost = fc["mu_shrunk"], fc["sigma_hat"], costs["cost_fraction"]
        if sg and abs(mu) < 0.15 * sg:
            add("SIGNAL_SMALL_VS_NOISE", "The edge is small next to the noise",
                f"The shrunk forecast ({pct(mu)}) is less than a sixth of a typical {ranking.get('h', 20)}-session move "
                f"(±{pct(sg, sign=False)}). Even if the model is right on average, any single month will be dominated by "
                "noise; the edge only shows up over many trades.", ("shrinkage", "sigma_hat"))
        if fc["shrink_factor"] is not None and fc["shrink_factor"] < 0.5:
            add("HEAVY_SHRINKAGE", "The model is unsure about this stock's signal",
                f"Only {fc['shrink_factor']:.0%} of the stock-specific forecast survives (its refits disagree, or the "
                "signal held up only partly out of sample). A large raw signal with heavy shrinkage is weak evidence.",
                ("se", "shrinkage"))
        if cost > abs(mu):
            add("COSTS_EXCEED_EDGE", "Costs are bigger than the expected edge",
                f"Round-trip cost {pct(cost, sign=False)} exceeds the size of the shrunk forecast ({pct(mu)}). Trading it would "
                "be expected to lose money even if the forecast is right.", ("round_trip_cost",))
        bigger = costs.get("bigger_accounts") or []
        if len(bigger) > 1 and bigger[0]["cost_fraction"] - bigger[-1]["cost_fraction"] > 0.0015:
            add("ACCOUNT_SIZE_MATTERS", "Your account size is part of the cost",
                f"At {rupees(bigger[0]['position'], 0)} the round trip costs {pct(bigger[0]['cost_fraction'], sign=False)}; at "
                f"{rupees(bigger[-1]['position'], 0)} it would be {pct(bigger[-1]['cost_fraction'], sign=False)}. The fixed "
                "₹15.34 DP charge and rupee rounding of STT weigh heavily on small positions.", ("dp_charge",))
        if fc["q10"] is not None and fc["q90"] is not None and fc["q10"] < 0 < fc["q90"]:
            add("RANGE_SPANS_ZERO", "Both outcomes are plausible",
                f"The 80% range runs from {pct(fc['q10'])} to {pct(fc['q90'])}: losing to the index is well within what "
                f"usually happens. P(beat the index) = {fc['p_positive']:.0%}.", ("interval", "p_positive"))
        con = card.get("contributions") or {}
        st = [i for i in con.get("items", []) if i["group"] == "stock" and i["contribution"] is not None]
        tot = sum(abs(i["contribution"]) for i in st)
        if st and tot > 0:
            big = max(st, key=lambda i: abs(i["contribution"]))
            if abs(big["contribution"]) > 0.5 * tot:
                add("ONE_SIGNAL_DOMINATES", "The call rests mainly on one signal",
                    f"{FEATURE_INFO[big['feature']]['name']} supplies {abs(big['contribution']) / tot:.0%} of the stock-specific "
                    "signal. If that one effect has stopped working, the forecast has little else behind it.", ("contribution",))
        mom = next((i for i in st if i["feature"] == "mom_12_1"), None)
        rev = next((i for i in st if i["feature"] in ("rev_5", "ret_20") and i["contribution"] and mom and mom["contribution"]
                    and (i["contribution"] > 0) != (mom["contribution"] > 0)), None)
        if mom and rev and abs(mom["contribution"]) > 0.001 and abs(rev["contribution"]) > 0.001:
            add("SIGNALS_CONFLICT", "Long-term and short-term signals disagree",
                f"{FEATURE_INFO['mom_12_1']['name']} {'adds' if mom['contribution'] > 0 else 'subtracts'} "
                f"{pct(abs(mom['contribution']), sign=False)} while {FEATURE_INFO[rev['feature']]['name']} "
                f"{'adds' if rev['contribution'] > 0 else 'subtracts'} {pct(abs(rev['contribution']), sign=False)}. "
                "Mixed signals usually mean a smaller, less reliable net forecast.", ("contribution",))
        if con.get("common_total") is not None and abs(con["common_total"]) > abs(con.get("stock_total") or 0):
            add("MARKET_PART_LARGER", "Most of the forecast is the market backdrop",
                f"The common part ({pct(con['common_total'])}) is larger than this stock's own part ({pct(con.get('stock_total'))}). "
                "The common part is identical for every stock today, so it says how the whole universe may do against the "
                "Nifty 50, not why this stock in particular.", ("common_part",))
    v = feats.get("vol_20")
    if v is not None and v * math.sqrt(250) > 0.5:
        add("HIGH_VOLATILITY", "A volatile stock",
            f"Daily volatility {pct(v, sign=False)} is about {pct(v * math.sqrt(250), 0, sign=False)} a year. Wide swings make "
            "both the tail gate and the forecast range harder to satisfy.", ("sigma_hat", "tail_gate"))
    r = feats.get("range_250")
    if r is not None and r >= 0.9:
        add("NEAR_YEAR_HIGH", "Near its 1-year high", f"It closed {r:.0%} of the way up its 1-year range.", ())
    elif r is not None and r <= 0.1:
        add("NEAR_YEAR_LOW", "Near its 1-year low", f"It closed only {r:.0%} of the way up its 1-year range.", ())
    med = card.get("median_value_20")
    if med is not None and med < 10 * 10_000_000 and card["class"] not in ("INELIGIBLE",):
        add("THIN_TRADING", "Thinner trading, higher slippage",
            f"Median traded value {crore(med)} is below ₹10 crore, so slippage is modelled at 0.25% each way instead of 0.10%.",
            ("slippage",))
    acts = card.get("actions") or []
    if acts:
        add("RECENT_CORPORATE_ACTION", "Recent corporate action",
            "Listed actions in the feature window: " + "; ".join(f"{a['ex_date']} {'/'.join(a['kinds'])}"
                                                                 + (f" factor {a['price_factor']:.4g}" if a.get('price_factor') else "")
                                                                 + f" ({a['status'].lower().replace('_', ' ')})" for a in acts[-3:])
            + ". Prices before the ex-date are restated in today's units for the features.", ("corporate_action",))
    d = ranking.get("data", {})
    ri = d.get("rule_inputs", {})
    if not ri.get("have_surveillance_file"):
        add("SURVEILLANCE_UNKNOWN", "Surveillance status unknown today",
            "The exchange's regulatory-indicator file for the next session was not admissible, so ASM/GSM status was not "
            "checked for any stock.", ("surveillance",))
    return out



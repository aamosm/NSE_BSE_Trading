def reason_text(code: str) -> str:
    if code in REASON_TEXT:
        return REASON_TEXT[code]
    if code.startswith("SERIES_"):
        return REASON_TEXT["SERIES"] + f" (series {code[7:]})."
    if code.startswith("BAND_"):
        return REASON_TEXT["BAND"] + f" (band {code[5:]}%)."
    if code.startswith("MODEL_UNAVAILABLE:"):
        return "No model could be fitted today: " + code.split(":", 1)[1].replace("_", " ").lower() + "."
    return code.replace("_", " ").capitalize() + "."



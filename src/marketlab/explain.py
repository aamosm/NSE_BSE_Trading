def _q(xs, p):
    xs = sorted(x for x in xs if x is not None)
    return xs[int(p * (len(xs) - 1))] if xs else None


def day_summary(ranking: dict) -> list[str]:
    """What the whole ranking says today and why, from counts and percentiles of numbers already in the cards."""
    r = ranking or {}
    stocks, counts, pol = r.get("stocks", []), r.get("counts", {}), r.get("policy", {})
    if not stocks:
        return ["No ranking yet."]
    # Both keys: a card restated at another capital keeps its forecast but loses its gates when the new capital
    # prices the stock out (one share above half the capital), and the gate counts below must not count those.
    fc = [s for s in stocks if s.get("forecast") and s.get("gates")]
    out = []
    buys, quals = counts.get("BUY_CANDIDATE", 0), counts.get("QUALIFIES", 0)
    if buys:
        names = ", ".join(s["symbol"] for s in sorted((s for s in stocks if s["class"] == "BUY_CANDIDATE"), key=lambda s: s.get("rank") or 9e9))
        out.append(f"{buys} buy candidate{'s' if buys > 1 else ''} today ({names}); {quals} more clear both gates but were not selected.")
    elif quals:
        out.append(f"No stock was selected, but {quals} clear both gates.")
    else:
        out.append("No stock clears both gates today, so the research view is: buy nothing and keep the cash.")
    if fc:
        tail = sum(1 for s in fc if "TAIL_LIMIT_AT_QUANTITY" in s["gates"]["at_quantity"])
        edge = sum(1 for s in fc if "EDGE_BELOW_COST_AT_QUANTITY" in s["gates"]["at_quantity"])
        sig = _q([s["forecast"]["sigma_hat"] for s in fc], 0.5)
        out.append(f"Risk is the main constraint: {tail} of {len(fc)} forecast stocks have a bad-month (10% outcome) that would cost the account more than "
                   f"the {pct(pol.get('tail_limit'), 0, sign=False)} limit after costs at their position size; the median stock's typical {r.get('h', 20)}-session "
                   f"move is ±{pct(sig, 1, sign=False)}.")
        mus = [s["forecast"]["mu_shrunk"] for s in fc]
        lo, hi = _q(mus, 0.05), _q(mus, 0.95)
        shrink = _q([s["forecast"]["shrink_factor"] for s in fc], 0.5)
        shrink_c = _q([s["forecast"].get("shrink_common") for s in fc if s["forecast"].get("shrink_common") is not None], 0.5) \
            if any(s["forecast"].get("shrink_common") is not None for s in fc) else None
        cost = _q([s["costs"]["cost_fraction"] for s in fc], 0.5)
        m = r.get("model") or {}
        out.append(f"The edge is too small to pay for trading: {edge} stocks fail the edge gate. After shrinkage, 90% of forecasts lie "
                   f"between {pct(lo)} and {pct(hi)}, while a round trip costs about {pct(cost, sign=False)} at your position size. "
                   + (f"Each forecast has a market-timing part (the same for every stock) and a stock-specific part; "
                      f"the model keeps about {shrink_c:.0%} of the first and {shrink:.0%} of the second, because the "
                      f"market-timing part rests on few independent months. " if shrink_c is not None else
                      f"The model keeps only about {shrink:.0%} of its raw forecasts because refits on resampled history "
                      f"disagree. ")
                   + f"It has {m.get('train_days', 'few')} training dates; more history is what would sharpen it.")
        best = sorted(fc, key=lambda s: -(s["gates"]["net_edge"] or -9))[:3]
        out.append("Closest to qualifying on edge: " + "; ".join(
            f"{s['symbol']} (forecast {pct(s['forecast']['mu_shrunk'])}, cost {pct(s['costs']['cost_fraction'], sign=False)}, "
            f"{CLASS_INFO[s['class']]['title'].lower()})" for s in best) + ".")
    flagged = [s for s in stocks if s["class"] == "AVOID" and not s.get("forecast")]
    model_avoid = counts.get("AVOID", 0) - len(flagged)
    if counts.get("AVOID"):
        from collections import Counter
        short = {"UNDER_SURVEILLANCE": "under exchange surveillance (ASM/GSM)", "SUSPENDED": "suspended",
                 "PERIODIC_CALL_AUCTION": "in periodic call auctions", "SURVEILLANCE_UNKNOWN": "with an unreadable surveillance status"}
        why = Counter("BAND" if s["reasons"][0].startswith("BAND_") else s["reasons"][0] for s in flagged)
        parts = [f"{n} {short.get(k, 'on a price band narrower than 10%' if k == 'BAND' else k.lower())}" for k, n in why.most_common()]
        if model_avoid:
            parts.append(f"{model_avoid} because the model expects them to lag the index by more than a buy would need to beat it")
        out.append(f"{counts['AVOID']} stocks are avoid: " + ", ".join(parts) + ".")
    inel = counts.get("INELIGIBLE", 0)
    if inel:
        from collections import Counter
        why = Counter(s["reasons"][0].split("_")[0] if s["reasons"][0].startswith("SERIES_") else s["reasons"][0]
                      for s in stocks if s["class"] == "INELIGIBLE")
        names = {"BELOW": "too thinly traded", "SERIES": "not EQ-series shares", "ETF": "ETFs", "PRICE": "priced above half your capital",
                 "NOT": "not traded every session"}
        out.append(f"{inel} listed securities are outside the universe: " + ", ".join(
            f"{n} {names.get(k.split('_')[0], k.lower())}" for k, n in why.most_common(4)) + ".")
    v = r.get("validation", {})
    if v.get("status") != "PROMOTED":
        out.append("All of this is an unvalidated research view: the walk-forward evaluation needs "
                   f"{v.get('sessions_needed_for_registered_evaluation')} sessions of history and {v.get('sessions_available')} are loaded.")
    return out



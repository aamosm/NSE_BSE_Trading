# ---- formatting ------------------------------------------------------------------------------------------

def pct(x, d=2, sign=True) -> str:
    if x is None or (isinstance(x, float) and not math.isfinite(x)):
        return "unknown"
    return f"{100 * x:+.{d}f}%" if sign else f"{100 * x:.{d}f}%"


def rupees(x, d=2) -> str:
    if x is None:
        return "unknown"
    return f"₹{float(x):,.{d}f}"


def crore(x) -> str:
    return "unknown" if x is None else f"₹{float(x) / 1e7:,.1f} crore"



def feature_table(card: dict) -> list[dict]:
    rows = []
    for f in features.FEATURES:
        info = FEATURE_INFO[f]
        rows.append({"feature": f, "name": info["name"], "raw": (card.get("features") or {}).get(f),
                     "x": (card.get("x") or {}).get(f), "units": info["units"], "what": info["what"]})
    return rows
